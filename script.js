            function searchMembers() {
                // Search input field theke value neya
                const input = document.getElementById('memberSearch').value.toLowerCase();
                // Shob member item-guloke select kora
                const memberItems = document.querySelectorAll('.member-item');
                // "No Results" message-er element-ti neya
                const noResults = document.getElementById('noResults');
                let found = 0;

                memberItems.forEach(item => {
                    // Protiti item-er name ebong role attributes check kora
                    const name = item.getAttribute('data-name').toLowerCase();
                    const role = item.getAttribute('data-role').toLowerCase();
                    
                    // Jodi name ba role search input-er sathe match kore
                    if (name.includes(input) || role.includes(input)) {
                        item.style.display = "block"; // Match korle dekhabe
                        found++;
                    } else {
                        item.style.display = "none"; // Match na korle hide korbe
                    }
                });

                // Jodi kono match na pawya jay, tobe message dekhabe
                if (found === 0) {
                    if(noResults) noResults.classList.remove('hidden');
                } else {
                    if(noResults) noResults.classList.add('hidden');
                }
};
